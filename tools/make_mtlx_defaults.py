#!/usr/bin/env python3
"""Generate hdPbrt/mtlxStdlib.inc from MaterialX's stdlib (stdlib_defs.mtlx,
stdlib_ng.mtlx) for the procedural displacement graph compiler
(hdPbrt/mtlxGraph.cpp): every nodedef's ports (node category, type, default
value, defaultgeomprop; Hydra passes authored inputs only) and every
nodegraph implementation (nodes, their inputs, outputs), so nodes the
compiler doesn't implement directly are expanded.

  tools/make_mtlx_defaults.py [<MaterialX libraries/stdlib dir>]
"""
import os, sys
import xml.etree.ElementTree as ET

lib = sys.argv[1] if len(sys.argv) > 1 else '/opt/hfs22.0.508/houdini/materialx/libraries/stdlib'
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', 'hdPbrt', 'mtlxStdlib.inc')


def q(s):
    return '"' + (s or '').replace('\\', '\\\\').replace('"', '\\"') + '"'


defs = ET.parse(os.path.join(lib, 'stdlib_defs.mtlx')).getroot()
ports = []
for nd in defs.iter('nodedef'):
    for el in nd:
        if el.tag in ('input', 'output'):
            ports.append('    {%s, %s, %s, %s, %s, %s, %s},' % (
                q(nd.get('name')), q(nd.get('node')), q(el.get('name')), q(el.get('type')),
                q(el.get('value', el.get('default', ''))), q(el.get('defaultgeomprop')),
                'true' if el.tag == 'output' else 'false'))

ngs = ET.parse(os.path.join(lib, 'stdlib_ng.mtlx')).getroot()
graph = []
for ng in ngs.iter('nodegraph'):
    nd = ng.get('nodedef')
    for node in ng:
        if node.tag == 'output':
            # graph output: node "" , input = output name
            graph.append('    {%s, "", "", %s, %s, "", %s, %s, ""},' % (
                q(nd), q(node.get('type')), q(node.get('name')),
                q(node.get('nodename')), q(node.get('output'))))
            continue
        if node.tag in ('input', 'parameter') or not isinstance(node.tag, str):
            continue
        inputs = [i for i in node if i.tag == 'input']
        # a node row (input "") then its inputs
        graph.append('    {%s, %s, %s, %s, "", "", "", "", ""},' % (
            q(nd), q(node.get('name')), q(node.tag), q(node.get('type'))))
        for i in inputs:
            graph.append('    {%s, %s, "", %s, %s, %s, %s, %s, %s},' % (
                q(nd), q(node.get('name')), q(i.get('type')), q(i.get('name')),
                q(i.get('value')), q(i.get('nodename')), q(i.get('output')),
                q(i.get('interfacename'))))

with open(out, 'w') as f:
    f.write('// Generated by tools/make_mtlx_defaults.py from MaterialX stdlib; do not edit.\n')
    f.write('#ifdef HDPBRT_MTLX_PORTS\n'
            '// {nodedef, node, port, type, value, defaultgeomprop, isOutput}\n')
    f.write('\n'.join(ports) + '\n#endif\n')
    f.write('#ifdef HDPBRT_MTLX_GRAPHS\n'
            '// {nodedef, node name, category (node row) or "" (input row; "" "" = graph '
            'output), type, input / output name, value, nodename, output, interfacename}\n')
    f.write('\n'.join(graph) + '\n#endif\n')
print(out, len(ports), 'ports', len(graph), 'graph rows')
